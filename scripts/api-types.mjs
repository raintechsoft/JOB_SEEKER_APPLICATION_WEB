import openapiTS, { astToString } from "openapi-typescript";
import { readFileSync, writeFileSync } from "node:fs";

const schema = new URL("../contracts/openapi/phase-11.json", import.meta.url);
const output = new URL("../src/types/generated/api.ts", import.meta.url);
const generated = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n" + astToString(await openapiTS(schema));
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== generated) {
    throw new Error("API types are stale. Run npm run api:types.");
  }
} else {
  writeFileSync(output, generated);
}
